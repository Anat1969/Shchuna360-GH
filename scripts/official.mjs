// Builds src/data/official.ts and the per-metric table of docs/measurement-rubric.md from
// docs/official-v2.json (the official "שכונה 360°" v2.0 requirements, extracted from the PDF).
// Run: node scripts/official.mjs
import { readFileSync, writeFileSync } from "node:fs";
const doc = JSON.parse(readFileSync("docs/official-v2.json", "utf8"));
const entries = doc.metrics
  .map((m) => `  ${m.id}: ${JSON.stringify({ intro: m.intro, requirements: m.requirements, stageC: m.stage_c, eligibility: m.eligibility })},`)
  .join("\n");
writeFileSync(
  "src/data/official.ts",
  `// Generated by scripts/official.mjs from docs/official-v2.json. Do not edit by hand.
export type Official = { intro: string; requirements: string; stageC: string; eligibility: string };
export const OFFICIAL_SOURCE = {
  title: "שכונה 360°: מדדים לתכנון ולפיתוח עירוני, גרסה 2.0, ינואר 2025",
  publisher: "המועצה הישראלית לבנייה ירוקה ומשרד הבינוי והשיכון",
  url: ${JSON.stringify(doc.url)},
};
export const OFFICIAL: Record<number, Official> = {
${entries}
};
`,
);
const rubric = readFileSync("docs/measurement-rubric.md", "utf8");
const head = rubric.slice(0, rubric.indexOf("## לפי מדד"));
const tail = rubric.slice(rubric.indexOf("## פלט לכל תוכנית"));
const cell = (t) => (t || "").replace(/\|/g, "/").replace(/\s+/g, " ").trim();
const table = [
  "## לפי מדד: הדרישות הרשמיות (שכונה 360° גרסה 2.0)",
  "",
  "הניקוד נקבע לפי הדרישות שבמסמך הרשמי. הטבלה נוצרת אוטומטית מ-docs/official-v2.json.",
  "",
  "| # | תת-נושא | מרבי | עמ׳ | מה מזכה בניקוד | בשלב ג׳ בנוסף | תנאי זכאות |",
  "|---|---|---|---|---|---|---|",
  ...doc.metrics.map((m) => `| ${m.id} | ${cell(m.intro).slice(0, 0)}${cell(titleOf(m.id))} | ${m.max} | ${m.page} | ${cell(m.requirements)} | ${cell(m.stage_c)} | ${cell(m.eligibility)} |`),
  "",
  ...doc.notes.map((n) => `- ${n}`),
  "",
  "",
].join("\n");
function titleOf(id) {
  const src = readFileSync("src/data/chapters.ts", "utf8");
  return src.match(new RegExp(`\\{ id: ${id}, name: "[^"]*", full: "((?:[^"\\\\]|\\\\.)*)"`))?.[1].replace(/\\"/g, '"') ?? "";
}
writeFileSync("docs/measurement-rubric.md", head + table + tail);
console.log(`official.ts: ${doc.metrics.length} metrics; rubric table rebuilt`);
